// Val vs Var
// Val ----> 
    // Val is value meaning cannot be REASSIGNED

// Var ----->
    // Var -> Can be reassigned. Is a Value Type



fun main(){

    val age = 55;
    // age = 11; // Error

    var name = "Vishal";
    name = "Vishal Singh"; 
    println("hii $age")
    println("hii $name")
}